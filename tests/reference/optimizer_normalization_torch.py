"""Writes tests/reference/optimizer_normalization_torch.hpp: PyTorch's results for small, exactly
representable inputs, used as known-answer tests for sgd, adam, adamw, layer_norm, rms_norm and
batch_norm (forward, backward, running statistics). The test is independent of PyTorch at run time;
rerun this script only when the cases change:

    python tests/reference/optimizer_normalization_torch.py > tests/reference/optimizer_normalization_torch.hpp
"""

import numpy as np
import torch
import torch.nn.functional as F

print("// Generated by optimizer_normalization_torch.py with PyTorch %s; do not edit." % torch.__version__)
print("// Inputs: x[i] = ((i*37) % 97 - 48) / 16, dy[i] = (((i*13) % 29) - 14) / 16, weight[j] = (1 + j % 5) / 4,")
print("// bias[j] = ((j % 3) - 1) / 8. Optimizers: p[i] = (i - 2) / 4, gradient of step t: ((i*7 + t*3) % 11 - 5) / 8.")
print("#pragma once")
print()
print("namespace torch_reference {")


def literal(v):
    text = "%.9g" % v
    if "." not in text and "e" not in text:
        text += ".0"  # a float literal needs a decimal point or an exponent before the suffix
    return text + "f"


def arr(name, t):
    a = t.detach().numpy().astype(np.float32).ravel()
    print("inline const float %s[] = {%s};" % (name, ", ".join(literal(v) for v in a)))


def x_of(n):
    return torch.tensor([((i * 37) % 97 - 48) / 16 for i in range(n)], dtype=torch.float32)


def dy_of(n):
    return torch.tensor([(((i * 13) % 29) - 14) / 16 for i in range(n)], dtype=torch.float32)


def scale_of(n):
    return torch.tensor([(1 + (j % 5)) / 4 for j in range(n)], dtype=torch.float32)


def bias_of(n):
    return torch.tensor([((j % 3) - 1) / 8 for j in range(n)], dtype=torch.float32)


# layer_norm and rms_norm over [3, 5], eps 1e-5
R, W = 3, 5
x = x_of(R * W).reshape(R, W).requires_grad_()
dy = dy_of(R * W).reshape(R, W)
w = scale_of(W).requires_grad_()
b = bias_of(W).requires_grad_()
y = F.layer_norm(x, (W,), w, b, 1e-5)
y.backward(dy)
arr("layer_y", y); arr("layer_dx", x.grad); arr("layer_dw", w.grad); arr("layer_db", b.grad)
x.grad = None
w.grad = None
y = F.rms_norm(x, (W,), w, 1e-5)
y.backward(dy)
arr("rms_y", y); arr("rms_dx", x.grad); arr("rms_dw", w.grad)

# batch_norm over [4, 3, 2], momentum 0.1, eps 1e-5, running stats start at (0.25, -0.5, 1) / (1.5, 0.75, 2)
N, C, S = 4, 3, 2
x = x_of(N * C * S).reshape(N, C, S).requires_grad_()
dy = dy_of(N * C * S).reshape(N, C, S)
w = scale_of(C).requires_grad_()
b = bias_of(C).requires_grad_()
rm = torch.tensor([0.25, -0.5, 1.0])
rv = torch.tensor([1.5, 0.75, 2.0])
y = F.batch_norm(x, rm, rv, w, b, True, 0.1, 1e-5)
y.backward(dy)
arr("bn_train_y", y); arr("bn_train_dx", x.grad); arr("bn_train_dw", w.grad); arr("bn_train_db", b.grad)
arr("bn_train_running_mean", rm); arr("bn_train_running_var", rv)
x.grad = None; w.grad = None; b.grad = None
rm = torch.tensor([0.25, -0.5, 1.0])
rv = torch.tensor([1.5, 0.75, 2.0])
y = F.batch_norm(x, rm, rv, w, b, False, 0.1, 1e-5)
y.backward(dy)
arr("bn_eval_y", y); arr("bn_eval_dx", x.grad); arr("bn_eval_dw", w.grad); arr("bn_eval_db", b.grad)

# batch_norm over [5, 3] (no spatial dimension), momentum 0.2
N, C = 5, 3
x = x_of(N * C).reshape(N, C).requires_grad_()
dy = dy_of(N * C).reshape(N, C)
rm = torch.tensor([0.25, -0.5, 1.0])
rv = torch.tensor([1.5, 0.75, 2.0])
y = F.batch_norm(x, rm, rv, w, b, True, 0.2, 1e-5)
y.backward(dy)
arr("bn2_y", y); arr("bn2_dx", x.grad); arr("bn2_running_mean", rm); arr("bn2_running_var", rv)


# optimizers: 6 parameters, three steps
def p0():
    return torch.tensor([(i - 2) / 4 for i in range(6)], dtype=torch.float32)


def grad_at(t):
    return torch.tensor([((i * 7 + t * 3) % 11 - 5) / 8 for i in range(6)], dtype=torch.float32)


cases = [
    ("sgd_momentum", lambda p: torch.optim.SGD([p], lr=0.1, momentum=0.9, weight_decay=0.01)),
    ("sgd_plain", lambda p: torch.optim.SGD([p], lr=0.1)),
    ("adam", lambda p: torch.optim.Adam([p], lr=0.01, weight_decay=0.1)),
    ("adamw", lambda p: torch.optim.AdamW([p], lr=0.01, weight_decay=0.1)),
]
for name, make in cases:
    p = p0().requires_grad_()
    opt = make(p)
    for t in (1, 2, 3):
        p.grad = grad_at(t).clone()
        opt.step()
    arr("opt_" + name, p)
    if name == "adam":
        state = opt.state[p]
        arr("opt_adam_m", state["exp_avg"])
        arr("opt_adam_v", state["exp_avg_sq"])
print()
print("} // namespace torch_reference")
